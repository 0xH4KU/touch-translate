import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

const root = new URL("../", import.meta.url);
const shared = ["utils", "settings", "provider", "cache", "gestures", "ui"];

export async function buildUserscript(kind) {
  if (!["text", "image"].includes(kind)) throw new Error(`Unknown script: ${kind}`);
  const files = [
    `${kind}/config`,
    ...shared.map((name) => `shared/${name}`),
    `${kind}/translation`,
    `${kind}/content`,
    ...(kind === "image" ? [`${kind}/viewer`] : []),
    `${kind}/jobs`,
    `${kind}/gestures`,
    `${kind}/styles`,
    `${kind}/index`,
  ];
  const [metadata, ...parts] = await Promise.all([
    readFile(new URL(`src/${kind}/metadata.js`, root), "utf8"),
    ...files.map((name) => readFile(new URL(`src/${name}.js`, root), "utf8")),
  ]);
  return `${metadata.trim()}\n\n// Generated by scripts/build.mjs. Edit src/ and rebuild.\n(() => {\n  "use strict";\n\n${parts.map((part, index) => `  // Source: src/${files[index]}.js\n\n${part.trimEnd()}`).join("\n\n")}\n})();\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.slice(2).some((arg) => arg !== "--check")) {
    throw new Error("Usage: node scripts/build.mjs [--check]");
  }
  for (const kind of ["text", "image"]) {
    const filename = kind === "text" ? "touch-translate.user.js" : "touch-image-translate.user.js";
    const output = new URL(filename, root);
    const generated = await buildUserscript(kind);
    if (process.argv.includes("--check")) {
      if (await readFile(output, "utf8") !== generated) {
        throw new Error(`${filename} is out of date. Run node scripts/build.mjs.`);
      }
    } else {
      await writeFile(output, generated);
    }
  }
  console.log(process.argv.includes("--check") ? "Userscripts are up to date" : "Built both userscripts");
}
